// Writes lib/l10n/app_localizations_override.dart: an AppLocalizations that prefers the wording
// changed from the dashboard and falls back to the built-in one, member by member.
//
// Run after `flutter gen-l10n` whenever strings change:
//   dart run tool/gen_text_overrides.dart
// and then, in the Laravel project, `php artisan app-texts:sync` so the dashboard lists them.
import 'dart:io';

void main() {
  final source = File('lib/l10n/app_localizations.dart').readAsStringSync();
  final getter = RegExp(r'^  String get (\w+);$', multiLine: true);
  final method = RegExp(r'^  String (\w+)\(([^)]*)\);$', multiLine: true);

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_text_overrides.dart. Do not edit by hand.')
    ..writeln()
    ..writeln("import 'app_localizations.dart';")
    ..writeln()
    ..writeln('/// The built-in wording, with any text changed from the dashboard in its place.')
    ..writeln('class OverriddenLocalizations extends AppLocalizations {')
    ..writeln('  OverriddenLocalizations(this._base, this._texts) : super(_base.localeName);')
    ..writeln()
    ..writeln('  final AppLocalizations _base;')
    ..writeln('  final Map<String, String> _texts;')
    ..writeln()
    ..writeln("  /// Puts the values into the dashboard's text, where it wrote `{name}`.")
    ..writeln('  String _fill(String key, Map<String, Object> values, String builtIn) {')
    ..writeln('    var text = _texts[key];')
    ..writeln('    if (text == null) return builtIn;')
    ..writeln("    values.forEach((name, value) => text = text!.replaceAll('{\$name}', '\$value'));")
    ..writeln('    return text!;')
    ..writeln('  }');

  for (final match in getter.allMatches(source)) {
    final name = match[1]!;
    out
      ..writeln()
      ..writeln('  @override')
      ..writeln("  String get $name => _texts['$name'] ?? _base.$name;");
  }

  for (final match in method.allMatches(source)) {
    final name = match[1]!;
    final params = match[2]!;
    final names = params.split(',').map((p) => p.trim().split(' ').last).toList();
    final values = names.map((n) => "'$n': $n").join(', ');
    out
      ..writeln()
      ..writeln('  @override')
      ..writeln('  String $name($params) => _fill(\'$name\', {$values}, _base.$name(${names.join(', ')}));');
  }

  out.writeln('}');
  File('lib/l10n/app_localizations_override.dart').writeAsStringSync(out.toString());
  stdout.writeln('${getter.allMatches(source).length} getters, ${method.allMatches(source).length} methods');
}
